#!/usr/bin/env node
// An MCP server over the orb catalog. Runs locally over stdio and needs no network.
//   node server.mjs        (SHADER_ORBS_DATA=/path/to/data to point at a different catalog folder)
import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { StdioServerTransport } from "@modelcontextprotocol/sdk/server/stdio.js";
import { existsSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { z } from "zod";

const here = dirname(fileURLToPath(import.meta.url));
const dataDir = process.env.SHADER_ORBS_DATA ?? join(here, "data");

if (!existsSync(join(dataDir, "catalog.json"))) {
  // stderr only: stdout is the protocol channel.
  console.error(`shader-orbs-mcp: no catalog at ${dataDir}. Run "npm run sync" first.`);
  process.exit(1);
}

// catalog.json and instructions.md are generated by the library (npm run agent) and copied here by sync.mjs.
const registry = { ...JSON.parse(readFileSync(join(dataDir, "catalog.json"), "utf8")) };
registry.name = registry.package;
registry.orbs = registry.orbs.map((o) => ({ ...o, title: o.title }));
const guide = readFileSync(join(dataDir, "instructions.md"), "utf8");

/** The catalog already holds everything about an orb. */
const detail = (slug) => registry.orbs.find((o) => o.slug === slug);

const norm = (s) => s.toLowerCase().replace(/[^a-z0-9]/g, "");
const findOrb = (input) => {
  const q = norm(input);
  return registry.orbs.find((o) => norm(o.slug) === q || norm(o.title) === q || norm(o.export) === q);
};

const text = (value) => ({ content: [{ type: "text", text: typeof value === "string" ? value : JSON.stringify(value, null, 2) }] });
const fail = (message) => ({ isError: true, content: [{ type: "text", text: message }] });
const unknownOrb = (slug) =>
  fail(`No orb called "${slug}". Orbs are ORB-01 to ORB-${String(registry.orbs.length).padStart(2, "0")} (slug "orb-01", export "orb01"). Use list_orbs to see them.`);

const server = new McpServer({ name: "shader-orbs", version: registry.version });

server.registerTool(
  "list_orbs",
  {
    title: "List orbs",
    description:
      "List the shader orbs. Pass a search word to filter by title, description or parameter name. Returns slug, title, description and parameter count.",
    inputSchema: { query: z.string().optional().describe('Optional filter, e.g. "lego", "plasma" or "exposure".') },
  },
  async ({ query }) => {
    const q = query ? norm(query) : "";
    const hits = registry.orbs.filter(
      (o) =>
        !q ||
        norm(`${o.title} ${o.description}`).includes(q) ||
        o.params.some((p) => norm(p.key).includes(q) || norm(p.label).includes(q))
    );
    if (!hits.length) {
      return text(`No orbs match "${query}".`);
    }
    return text(hits.map((o) => ({ slug: o.slug, title: o.title, description: o.description, parameters: o.params.length })));
  }
);

server.registerTool(
  "get_orb",
  {
    title: "Get an orb",
    description:
      "Everything about one orb: its parameters (key, label, range, default, whether it is an integrated phase clock), colors, moods, per-mood presets, and a usage snippet.",
    inputSchema: { slug: z.string().describe('The orb: "orb-01", "ORB-01" or "orb01".') },
  },
  async ({ slug }) => {
    const orb = findOrb(slug);
    return orb ? text(detail(orb.slug)) : unknownOrb(slug);
  }
);

server.registerTool(
  "find_by_parameter",
  {
    title: "Find orbs by parameter",
    description:
      "Find the orbs that have a parameter whose key or label contains a word (e.g. exposure, spin, lattice), with that parameter's range and default on each.",
    inputSchema: { query: z.string().describe("Part of a parameter key or label.") },
  },
  async ({ query }) => {
    const q = norm(query);
    const hits = registry.orbs
      .map((o) => ({
        orb: o.title,
        slug: o.slug,
        parameters: o.params
          .filter((p) => norm(p.key).includes(q) || norm(p.label).includes(q))
          .map((p) => ({ key: p.key, label: p.label, min: p.min, max: p.max, default: p.default, integrated: p.integrated })),
      }))
      .filter((h) => h.parameters.length);
    return hits.length ? text(hits) : text(`No orb has a parameter matching "${query}".`);
  }
);

server.registerTool(
  "build_snippet",
  {
    title: "Build a <ShaderOrb /> snippet",
    description:
      "Write a <ShaderOrb /> snippet for an orb. Unknown parameter or color keys are rejected, and values outside a parameter's range are clamped and reported, so the code is always valid.",
    inputSchema: {
      slug: z.string().describe('The orb: "orb-01", "ORB-01" or "orb01".'),
      state: z.enum(["idle", "thinking", "speaking"]).optional(),
      params: z.record(z.string(), z.number()).optional().describe("Parameter values by key."),
      colors: z.record(z.string(), z.string()).optional().describe("Hex colors by key, e.g. { tint: '#66ccff' }."),
      volumes: z
        .object({ input: z.number().min(0).max(1).optional(), output: z.number().min(0).max(1).optional() })
        .optional(),
      size: z.number().positive().optional(),
      interactive: z.boolean().optional().describe("Default true."),
    },
  },
  async ({ slug, state, params, colors, volumes, size, interactive = true }) => {
    const found = findOrb(slug);
    if (!found) {
      return unknownOrb(slug);
    }
    const orb = detail(found.slug);
    const notes = [];

    const byKey = new Map(orb.params.map((p) => [p.key, p]));
    const validParams = {};
    for (const [key, value] of Object.entries(params ?? {})) {
      const def = byKey.get(key);
      if (!def) {
        return fail(`${orb.title} has no parameter "${key}". Its parameters are: ${orb.params.map((p) => p.key).join(", ")}.`);
      }
      const clamped = Math.min(def.max, Math.max(def.min, value));
      if (clamped !== value) {
        notes.push(`${key}: ${value} is outside ${def.min} to ${def.max}, so it was clamped to ${clamped}.`);
      }
      validParams[key] = Number(clamped.toFixed(3));
    }

    const validColors = {};
    for (const [key, value] of Object.entries(colors ?? {})) {
      if (!orb.colors.some((c) => c.key === key)) {
        return fail(`${orb.title} has no color "${key}". Its colors are: ${orb.colors.map((c) => c.key).join(", ") || "none"}.`);
      }
      if (!/^#([0-9a-f]{3}|[0-9a-f]{6})$/i.test(value)) {
        return fail(`Color "${key}" must be a hex string like #66ccff, got "${value}".`);
      }
      validColors[key] = value;
    }

    const lines = [`import { ShaderOrb, ${orb.export} } from "${registry.name}";`, "", "<ShaderOrb", `  orb={${orb.export}}`];
    if (size && size !== 280) lines.push(`  size={${size}}`);
    if (state && state !== "idle") lines.push(`  state="${state}"`);
    if (Object.keys(validParams).length) {
      lines.push("  params={{", ...Object.entries(validParams).map(([k, v]) => `    ${k}: ${v},`), "  }}");
    }
    if (Object.keys(validColors).length) {
      lines.push("  colors={{", ...Object.entries(validColors).map(([k, v]) => `    ${k}: "${v}",`), "  }}");
    }
    if (volumes && (volumes.input !== undefined || volumes.output !== undefined)) {
      const v = [volumes.input !== undefined && `input: ${volumes.input}`, volumes.output !== undefined && `output: ${volumes.output}`].filter(Boolean);
      lines.push(`  volumes={{ ${v.join(", ")} }}`);
    }
    if (interactive) lines.push("  interactive");
    lines.push("/>");

    const reminders = [
      "Needs a development build (not Expo Go).",
      "The shaders are non-commercial unless you have XorDev's permission.",
    ];
    return text([lines.join("\n"), ...(notes.length ? ["", "Notes:", ...notes.map((n) => `- ${n}`)] : []), "", ...reminders.map((r) => `- ${r}`)].join("\n"));
  }
);

server.registerTool(
  "get_guide",
  {
    title: "Usage guide",
    description:
      "The full instructions for using react-native-shader-orbs correctly: license check, install, how to pick parameters, performance rules and troubleshooting. Read this before writing orb code.",
    inputSchema: {},
  },
  async () => text(guide)
);

server.registerResource(
  "guide",
  "shader-orbs://guide",
  { title: "react-native-shader-orbs usage guide", mimeType: "text/markdown" },
  async (uri) => ({ contents: [{ uri: uri.href, mimeType: "text/markdown", text: guide }] })
);

server.registerTool(
  "get_install",
  {
    title: "Install and requirements",
    description: "How to install the package, what it requires, its status, and the licensing caveat for the shaders.",
    inputSchema: {},
  },
  async () =>
    text({
      package: registry.name,
      version: registry.version,
      install: "npx expo install react-native-shader-orbs react-native-webgpu react-native-reanimated react-native-worklets",
      configPlugin: 'Add "react-native-webgpu" to the plugins array in app.json, then rebuild the development build (npx expo run:android).',
      requirements: registry.requirements,
      license: registry.license,
    })
);

await server.connect(new StdioServerTransport());
